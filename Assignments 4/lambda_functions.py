# Lambda Functions in Python


# addition
add = lambda a, b : a + b

print(f"Addition :{add(10, 20)}")




# subtraction
subtraction = lambda a, b = 5 : a - b

print(f"Subtraction :{subtraction(10)}")



# multiplication
multiplication = lambda a, b : a * b

print(f"multiplication :{multiplication(2, 3)}")



# division
division = lambda a, b : a % b

print(f"Division: {division(10, 3)}")